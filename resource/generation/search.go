// Search over resources (README section 4): the schema states the facts and the
// generator derives the vocabulary. A table's hidden TOKENLIST columns, each generated
// by TOKENIZE_SUBSTRING over a column in one of three shapes (the column itself, its
// digits, or its date as YYYYMMDD), carried by the table's one search index, give the
// columns' fields their matches and a place in the resource's search box: the search
// fact. A stored LOWER(col) column that leads an index, or sits after the tenant column
// in one, gives its field a case-folded startswith: the prefix fact. Both are written
// onto the list and read request structs as the search tag (resource.SearchSpec) and
// into the TypeScript metadata; a view's author names the table column whose fact a
// field carries, since the generator cannot read a view's projection; and a computed
// resource's allow_filter text fields are evaluated in memory. @searchAlso adds a
// child table's text to a parent's box, one hop down a foreign key.

const (
	// searchIndexType is INFORMATION_SCHEMA.INDEXES.INDEX_TYPE for a search index.
	searchIndexType = "SEARCH"
	// tokenListType is INFORMATION_SCHEMA.COLUMNS.SPANNER_TYPE for a TOKENLIST column.
	tokenListType = "TOKENLIST"

	// The tokenizers and the functions the generation expressions are read through.
	tokenizeSubstringFunc = "TOKENIZE_SUBSTRING" //nolint:gosec // the name of a Spanner function, not a credential
	regexpReplaceFunc     = "REGEXP_REPLACE"
	formatDateFunc        = "FORMAT_DATE"
	formatTimestampFunc   = "FORMAT_TIMESTAMP"
	lowerFunc             = "LOWER"
	// digitsPattern is the regular expression a digits role strips with, as the DDL
	// writes it: everything that is not a digit.
	digitsPattern = `\D`
	// dateFormat is the format a date role formats with: YYYYMMDD.
	dateFormat = "%Y%m%d"

	// The named arguments of TOKENIZE_SUBSTRING the generator reads, and the ones it
	// accepts without reading.
	relativeSearchTypesArg = "relative_search_types"
	shortTokensArg         = "short_tokens_only_for_anchors"
	removeDiacriticsArg    = "remove_diacritics"
	valuePrefixType        = "value_prefix"
	valueSuffixType        = "value_suffix"

	// searchViaArgKey names the foreign key a @searchAlso joins through when the child
	// has several to the parent.
	searchViaArgKey = "via"
)

// ignoredTokenizers are the tokenizers a TOKENLIST column may be generated by that
// state no search fact: a word or n-gram index serves other queries, and the column is
// left alone.
var ignoredTokenizers = []string{"TOKENIZE_FULLTEXT", "TOKENIZE_NGRAMS", "TOKENIZE_NUMBER", "TOKENIZE_BOOL", "TOKENIZE_JSON", "TOKEN", "TOKENLIST_CONCAT"}

// acceptedTokenizerArgs are TOKENIZE_SUBSTRING's named arguments the generator accepts
// without reading, beside the three it reads.
var acceptedTokenizerArgs = []string{"ngram_size_min", "ngram_size_max", "language_tag", "content_type"}

// tokenFact is one TOKENLIST column's reading of its generation expression.
type tokenFact struct {
	// Column is the TOKENLIST column and Source the column it tokenizes.
	Column string
	Source string
	Role   resource.SearchRole
	// Anchors are the relative search types declared, Contains whether an unanchored
	// match is answered (false under short_tokens_only_for_anchors), Diacritics whether
	// remove_diacritics is set, and Zone the time zone a timestamp is formatted in.
	Anchors    []resource.SearchAnchor
	Contains   bool
	Diacritics bool
	Zone       string
	// Index is the search index carrying the column, and Partitions that index's
	// non-token key columns, the PARTITION BY columns.
	Index      string
	Partitions []string
	Storing    []string
}

// tableSearch is a table's search facts: by source column, the token column tokenizing
// it, and by source column, the lowercased stored column that gives the prefix fact.
type tableSearch struct {
	tokens map[string]*tokenFact
	lower  map[string]string
	// index is the table's search index, nil when it declares none, and partitions
	// its non-token key columns, the PARTITION BY columns.
	index      *indexMeta
	partitions []string
}

// parseTokenExpression reads a TOKENLIST column's generation expression. It answers nil
// for a tokenizer that states no search fact, the fact for the three substring shapes,
// and an error for any other expression, so a search index the generator cannot read
// is refused rather than half-read.
func parseTokenExpression(column, expression string) (*tokenFact, error) {
	expr, err := memefish.ParseExpr("", expression)
	if err != nil {
		return nil, errors.Wrapf(err, "column %s: the generation expression %q does not parse", column, expression)
	}
	call, ok := expr.(*ast.CallExpr)
	if !ok {
		return nil, errors.Newf("column %s is generated by %q, which is not a tokenizer call", column, expression)
	}
	name := strings.ToUpper(call.Func.SQL())
	if slices.Contains(ignoredTokenizers, name) {
		return nil, nil
	}
	if name != tokenizeSubstringFunc {
		return nil, errors.Newf("column %s is generated by %s, which the generator does not read; the search facts come from %s", column, name, tokenizeSubstringFunc)
	}
	if len(call.Args) != 1 {
		return nil, errors.Newf("column %s: %s takes the tokenized expression as its one positional argument", column, tokenizeSubstringFunc)
	}
	fact := &tokenFact{Column: column, Contains: true, Role: resource.SearchRoleText}
	if err := fact.readSource(argExpr(call.Args[0])); err != nil {
		return nil, errors.Wrapf(err, "column %s", column)
	}
	for _, named := range call.NamedArgs {
		if err := fact.readNamedArg(named); err != nil {
			return nil, errors.Wrapf(err, "column %s", column)
		}
	}

	return fact, nil
}

// argExpr unwraps a call argument to its expression, nil for the other argument kinds.
func argExpr(arg ast.Arg) ast.Expr {
	if a, ok := arg.(*ast.ExprArg); ok {
		return a.Expr
	}

	return nil
}

// readSource reads the tokenized expression: a column (text), REGEXP_REPLACE over the
// column with r'\D' and the empty string (digits), FORMAT_DATE('%Y%m%d', col) or
// FORMAT_TIMESTAMP('%Y%m%d', col, zone) (date; a timestamp names the zone its day is
// read in).
func (f *tokenFact) readSource(expr ast.Expr) error {
	if column, ok := columnName(expr); ok {
		f.Source = column

		return nil
	}
	call, ok := expr.(*ast.CallExpr)
	if !ok {
		return errors.Newf("%s tokenizes %s, which is not a column, the column's digits (%s(col, r'%s', '')) or its date (%s('%s', col))", tokenizeSubstringFunc, sqlOf(expr), regexpReplaceFunc, digitsPattern, formatDateFunc, dateFormat)
	}
	args := make([]ast.Expr, 0, len(call.Args))
	for _, arg := range call.Args {
		args = append(args, argExpr(arg))
	}
	switch name := strings.ToUpper(call.Func.SQL()); name {
	case regexpReplaceFunc:
		if len(args) != 3 || stringValue(args[1]) != digitsPattern || stringValue(args[2]) != "" {
			return errors.Newf("%s reads a column's digits as %s(col, r'%s', ''), not %s", tokenizeSubstringFunc, regexpReplaceFunc, digitsPattern, sqlOf(expr))
		}
		column, ok := columnName(args[0])
		if !ok {
			return errors.Newf("%s strips the digits of %s, which is not a column", regexpReplaceFunc, sqlOf(args[0]))
		}
		f.Source, f.Role = column, resource.SearchRoleDigits
	case formatDateFunc, formatTimestampFunc:
		if len(args) < 2 || len(args) > 3 || stringValue(args[0]) != dateFormat || (name == formatDateFunc && len(args) == 3) {
			return errors.Newf("%s reads a date as %s('%s', col), or a timestamp as %s('%s', col, zone), not %s", tokenizeSubstringFunc, formatDateFunc, dateFormat, formatTimestampFunc, dateFormat, sqlOf(expr))
		}
		column, ok := columnName(args[1])
		if !ok {
			return errors.Newf("%s formats %s, which is not a column", name, sqlOf(args[1]))
		}
		f.Source, f.Role = column, resource.SearchRoleDate
		if name == formatTimestampFunc {
			// Without a zone the day is the database's default zone's (America/Los_Angeles
			// on Spanner), which nothing reading the token column back can know; the
			// schema names the zone the day is read in.
			if len(args) != 3 {
				return errors.Newf("%s('%s', %s) names no time zone, so the day is the database's default zone's; write %s('%s', %s, 'UTC') or the zone the day is read in", name, dateFormat, column, name, dateFormat, column)
			}
			zone := stringValue(args[2])
			if zone == "" {
				return errors.Newf("%s names the zone %s, which is not a string literal", name, sqlOf(args[2]))
			}
			f.Zone = zone
		}
	default:
		return errors.Newf("%s tokenizes %s(…), which is not a column, the column's digits (%s) or its date (%s, %s)", tokenizeSubstringFunc, name, regexpReplaceFunc, formatDateFunc, formatTimestampFunc)
	}

	return nil
}

// readNamedArg reads one named argument of TOKENIZE_SUBSTRING.
func (f *tokenFact) readNamedArg(named *ast.NamedArg) error {
	name := strings.ToLower(named.Name.Name)
	switch name {
	case relativeSearchTypesArg:
		array, ok := named.Value.(*ast.ArrayLiteral)
		if !ok {
			return errors.Newf("%s => %s is not an array of search types", relativeSearchTypesArg, sqlOf(named.Value))
		}
		for _, value := range array.Values {
			switch stringValue(value) {
			case valuePrefixType:
				f.Anchors = append(f.Anchors, resource.SearchAnchorPrefix)
			case valueSuffixType:
				f.Anchors = append(f.Anchors, resource.SearchAnchorSuffix)
			default:
				// A word or phrase search type serves the full-text functions; the
				// substring matches do not read it.
			}
		}
	case shortTokensArg:
		if boolValue(named.Value) {
			f.Contains = false
		}
	case removeDiacriticsArg:
		f.Diacritics = boolValue(named.Value)
	default:
		if !slices.Contains(acceptedTokenizerArgs, name) {
			return errors.Newf("%s names the argument %s, which the generator does not know", tokenizeSubstringFunc, named.Name.Name)
		}
	}

	return nil
}

// columnName reads a bare column reference: an identifier, or a one-part path.
func columnName(expr ast.Expr) (string, bool) {
	switch n := expr.(type) {
	case *ast.Ident:
		return n.Name, true
	case *ast.Path:
		if len(n.Idents) == 1 {
			return n.Idents[0].Name, true
		}
	}

	return "", false
}

// stringValue reads a string literal's value, "" for anything else.
func stringValue(expr ast.Expr) string {
	if s, ok := expr.(*ast.StringLiteral); ok {
		return s.Value
	}

	return ""
}

// boolValue reads a boolean literal's value, false for anything else.
func boolValue(expr ast.Expr) bool {
	if b, ok := expr.(*ast.BoolLiteral); ok {
		return b.Value
	}

	return false
}

// sqlOf renders an expression for a message, "" for nil.
func sqlOf(expr ast.Expr) string {
	if expr == nil {
		return ""
	}

	return expr.SQL()
}

// parseLowerExpression reads a generated column's expression as LOWER(col), answering
// the column it lowercases; "" where the expression is anything else.
func parseLowerExpression(expression string) string {
	expr, err := memefish.ParseExpr("", expression)
	if err != nil {
		return ""
	}
	call, ok := expr.(*ast.CallExpr)
	if !ok || strings.ToUpper(call.Func.SQL()) != lowerFunc || len(call.Args) != 1 {
		return ""
	}
	column, _ := columnName(argExpr(call.Args[0]))

	return column
}

// tableSearchFacts reads a table's search facts off its generated columns and its
// indexes. tenantColumn is the bare @domain column of the resource the table backs, ""
// for a global table or a table read for a view; anySecond admits a lowercased column
// second in any index key as the prefix fact, for a view whose tenant the generator
// does not know. The refusals: two search indexes on one table, a substring token
// column in no search index, two token columns over one source column, an expression
// the generator cannot read, and a search index partitioned by anything but the tenant
// column.
func tableSearchFacts(table string, meta *tableMetadata, tenantColumn string, anySecond bool) (*tableSearch, error) {
	facts := &tableSearch{tokens: make(map[string]*tokenFact), lower: make(map[string]string)}
	for _, index := range meta.Indexes {
		if !index.Search {
			continue
		}
		if facts.index != nil {
			return nil, errors.Newf("table %s declares two search indexes, %s and %s; a table serves its search box from one", table, facts.index.Name, index.Name)
		}
		facts.index = &index
	}

	tokenColumns := make(map[string]struct{})
	for _, name := range slices.Sorted(maps.Keys(meta.Columns)) {
		column := meta.Columns[name]
		if column.GenerationExpression == "" {
			continue
		}
		if column.SpannerType != tokenListType {
			if source := parseLowerExpression(column.GenerationExpression); source != "" && leadsIndex(meta, name, tenantColumn, anySecond) {
				facts.lower[source] = name
			}

			continue
		}
		fact, err := parseTokenExpression(name, column.GenerationExpression)
		if err != nil {
			return nil, errors.Wrapf(err, "table %s", table)
		}
		if fact == nil {
			continue
		}
		if facts.index == nil || !slices.ContainsFunc(facts.index.Key, func(k indexColumn) bool { return k.Column == name }) {
			return nil, errors.Newf("table %s: the token column %s is in no search index, so nothing serves a search through it; add it to the table's search index, or drop the column", table, name)
		}
		if prior, dup := facts.tokens[fact.Source]; dup {
			return nil, errors.Newf("table %s: the token columns %s and %s both tokenize %s; a column has one token column, so a search over it has one reading", table, prior.Column, name, fact.Source)
		}
		fact.Index = facts.index.Name
		fact.Storing = facts.index.Storing
		facts.tokens[fact.Source] = fact
		tokenColumns[name] = struct{}{}
	}

	if facts.index != nil {
		for _, key := range facts.index.Key {
			if meta.Columns[key.Column].SpannerType != tokenListType {
				facts.partitions = append(facts.partitions, key.Column)
			}
		}
		if tenantColumn != "" && len(facts.partitions) > 0 && facts.partitions[0] != tenantColumn {
			return nil, errors.Newf("table %s: the search index %s is partitioned by %s, and the resource's tenant column is %s; a tenant-scoped resource's search index is partitioned by its tenant column, so a search reads one tenant's tokens", table, facts.index.Name, facts.partitions[0], tenantColumn)
		}
		for _, fact := range facts.tokens {
			fact.Partitions = facts.partitions
		}
	}

	return facts, nil
}

// indexStoring lists the columns an index of a table stores, nil when the table or the
// index is unknown.
func (c *client) indexStoring(table, indexName string) []string {
	meta, ok := c.tableMap[table]
	if !ok {
		return nil
	}
	for _, index := range meta.Indexes {
		if index.Name == indexName {
			return index.Storing
		}
	}

	return nil
}

// leadsIndex reports whether a column leads a seek index of the table, or sits directly
// after the tenant column in one (any second position where anySecond): the positions
// a filter on the column alone seeks from (deriveIndexFlags, deriveTenantIndexFlags).
func leadsIndex(meta *tableMetadata, column, tenantColumn string, anySecond bool) bool {
	for _, index := range meta.Indexes {
		if index.Search || index.NullFiltered || len(index.Key) == 0 {
			continue
		}
		if index.Key[0].Column == column {
			return true
		}
		if len(index.Key) > 1 && index.Key[1].Column == column && (anySecond || (tenantColumn != "" && index.Key[0].Column == tenantColumn)) {
			return true
		}
	}

	return false
}

// generatedColumnRefusal is the refusal a table field over a generated column earns: a
// TOKENLIST column is the search index's and no field carries it, and a generated
// column is output-only by derivation, so restating output_only is refused as the other
// derived facts' restatements are. ok is false for every other field.
func generatedColumnRefusal(field *parser.Field, column *columnMeta) (refusal string, ok bool) {
	if column.SpannerType == tokenListType {
		return fmt.Sprintf("the column is a %s column, which the table's search index reads and no field carries; drop the field", tokenListType), true
	}
	if column.GenerationExpression == "" {
		return "", false
	}
	if tag, ok := field.LookupTag(conditionsTagKey); ok && slices.Contains(strings.Split(tag, ","), outputOnlyCondition) {
		return fmt.Sprintf("the column is generated by the database (%s), so the field is output-only by derivation; drop %s:%q", column.GenerationExpression, conditionsTagKey, outputOnlyCondition), true
	}

	return "", false
}

// searchAlsoDecl is one @searchAlso as written: the child field, Child.Field, and the
// foreign key named by via:, "" when the child has one to the parent.
type searchAlsoDecl struct {
	target string
	via    string
}

// searchBranch is one resolved @searchAlso: what the generated SearchBranches method
// declares (resource.SearchBranch), with the child's generator-side facts.
type searchBranch struct {
	resource.SearchBranch
	// child is the child resource and field the declaration named.
	child      *resourceInfo
	childField *resourceField
}

// GoLiteral renders the branch as the resource.SearchBranch literal the generated
// method returns.
func (b *searchBranch) GoLiteral() string {
	anchors := make([]string, 0, len(b.Anchors))
	for _, anchor := range b.Anchors {
		anchors = append(anchors, "resource.SearchAnchor"+strings.ToUpper(string(anchor)[:1])+string(anchor)[1:])
	}
	anchorList := "nil"
	if len(anchors) > 0 {
		anchorList = "[]resource.SearchAnchor{" + strings.Join(anchors, ", ") + "}"
	}

	return fmt.Sprintf("{Name: %q, Resource: %q, Field: %q, Tag: %q, Table: %q, Column: %q, JoinColumn: %q, TenantColumn: %q, Token: %q, Index: %q, Role: %s, Anchors: %s, Contains: %t, Zone: %q, PII: %t}",
		b.Name, b.Resource, b.Field, b.Tag, b.Table, b.Column, b.JoinColumn, b.TenantColumn, b.Token, b.Index, "resource.SearchRole"+strings.ToUpper(string(b.Role)[:1])+string(b.Role)[1:], anchorList, b.Contains, b.Zone, b.PII)
}

// searchAlsoArgSpec is @searchAlso's argument shape: the child field, then via:.
func searchAlsoArgSpec() *genlang.ArgSpec {
	return &genlang.ArgSpec{Positional: 1, Keys: []string{searchViaArgKey}}
}

// parseSearchAlso reads a struct's @searchAlso declarations as written.
func parseSearchAlso(structName string, annotations genlang.StructAnnotations) ([]searchAlsoDecl, error) {
	if !annotations.Struct.Has(searchAlsoKeyword) {
		return nil, nil
	}
	invocations, err := annotations.Struct.Get(searchAlsoKeyword).ParseInvocations(searchAlsoArgSpec())
	if err != nil {
		return nil, errors.Wrapf(err, "struct %s: @%s", structName, searchAlsoKeyword)
	}
	decls := make([]searchAlsoDecl, 0, len(invocations))
	for _, invocation := range invocations {
		target := strings.TrimSpace(invocation.Positional[0])
		if child, field, ok := strings.Cut(target, "."); !ok || child == "" || field == "" || strings.Contains(field, ".") {
			return nil, errors.Newf("struct %s: @%s(%s) names a child field as Child.Field, the child struct and its field, one hop down a foreign key", structName, searchAlsoKeyword, target)
		}
		via, _ := invocation.Named(searchViaArgKey)
		decls = append(decls, searchAlsoDecl{target: target, via: strings.TrimSpace(via)})
	}

	return decls, nil
}

// rejectSearchAlso refuses @searchAlso on every kind but a table-backed resource: a
// view's and a computed resource's box have no key set a child branch joins into.
func rejectSearchAlso(pStruct *parser.Struct, annotations genlang.StructAnnotations, kind string) error {
	if annotations.Struct.Has(searchAlsoKeyword) {
		return errors.Newf("struct %s: @%s is declared on a table-backed resource, whose search box joins the child's rows through its key; a %s declares none", pStruct.Name(), searchAlsoKeyword, kind)
	}

	return nil
}

// SearchPartitionWarning says a tenant-scoped resource's search index is not
// partitioned: every search reads every tenant's tokens for the term, then filters to
// the tenant. Index is the CREATE SEARCH INDEX the resource wants.
type SearchPartitionWarning struct {
	Resource     string
	Table        string
	IndexName    string
	TenantColumn string
}

func (SearchPartitionWarning) warning() {}

// String renders the one-line warning, names verbatim from the schema.
func (w SearchPartitionWarning) String() string {
	return fmt.Sprintf("%s searches through %s on %s, which is not partitioned, so every search reads every tenant's tokens; wanted: PARTITION BY %s on the index", w.Resource, w.IndexName, w.Table, w.TenantColumn)
}

// SearchBranchStoringWarning says a @searchAlso child's search index does not store
// the foreign key the branch joins through, so every matching child row is read back
// from the base table for its key.
type SearchBranchStoringWarning struct {
	Resource   string
	Child      string
	IndexName  string
	JoinColumn string
}

func (SearchBranchStoringWarning) warning() {}

// String renders the one-line warning, names verbatim from the schema.
func (w SearchBranchStoringWarning) String() string {
	return fmt.Sprintf("%s searches %s through %s, which does not store %s, so every matching %s row is read back for its key; wanted: STORING (%s) on the index", w.Resource, w.Child, w.IndexName, w.JoinColumn, w.Child, w.JoinColumn)
}

// resolveSearchFacts derives a table-backed resource's search vocabulary from its
// table: each field over a tokenized column takes the search fact, each over a
// lowercased column the prefix fact, and the @searchAlso declarations are kept for
// resolveSearchBranches. The field's type is checked against the role: a text or
// digits role reads a text field, a date role a date or timestamp field.
func (c *client) resolveSearchFacts(res *resourceInfo, pStruct *parser.Struct, annotations genlang.StructAnnotations, table *tableMetadata) error {
	decls, err := parseSearchAlso(pStruct.Name(), annotations)
	if err != nil {
		return err
	}
	res.searchAlso = decls

	tenantColumn := bareTenantColumn(res)
	facts, err := tableSearchFacts(c.pluralize(res.Name()), table, tenantColumn, false)
	if err != nil {
		return errors.Wrapf(err, "struct %s", pStruct.Name())
	}
	if facts.index != nil && tenantColumn != "" && len(facts.partitions) == 0 {
		res.searchWarnings = append(res.searchWarnings, SearchPartitionWarning{Resource: res.Name(), Table: c.pluralize(res.Name()), IndexName: facts.index.Name, TenantColumn: tenantColumn})
	}

	return applySearchFacts(res, facts, pStruct.Name())
}

// bareTenantColumn is the resource's bare @domain column, "" for a global resource or
// one resolving its tenant through a join path.
func bareTenantColumn(res *resourceInfo) string {
	if res.DomainBinding == nil || len(res.DomainBinding.Path) > 0 {
		return ""
	}

	return fieldColumn(res.DomainBinding.Anchor)
}

// applySearchFacts writes a table's facts onto the resource's fields by column.
func applySearchFacts(res *resourceInfo, facts *tableSearch, structName string) error {
	for _, field := range res.Fields {
		column := fieldColumn(field)
		fact, hasToken := facts.tokens[column]
		lower, hasLower := facts.lower[column]
		if !hasToken && !hasLower {
			continue
		}
		spec := &resource.SearchSpec{Lower: lower}
		if hasToken {
			if err := checkSearchFieldType(field, fact); err != nil {
				return errors.Wrapf(err, "struct %s field %s", structName, field.Name())
			}
			spec.Token, spec.Index, spec.Role = fact.Column, fact.Index, fact.Role
			spec.Anchors, spec.Contains, spec.Diacritics, spec.Zone = fact.Anchors, fact.Contains, fact.Diacritics, fact.Zone
		} else if kind, slice := valueKindOf(field.GoType()); kind != resource.ValueKindString || slice {
			// A lowercased column over anything but text is not the prefix fact.
			continue
		}
		field.Search = spec
	}

	return nil
}

// checkSearchFieldType refuses a token fact over a field whose type does not fit its
// role: text and digits read a text field, date a date or timestamp field.
func checkSearchFieldType(field *resourceField, fact *tokenFact) error {
	kind, slice := valueKindOf(field.GoType())
	typeName := typeStringer(field.GoType())
	switch fact.Role {
	case resource.SearchRoleDate:
		if !strings.Contains(typeName, "time.Time") && !strings.Contains(typeName, "civil.Date") && !strings.Contains(typeName, "spanner.NullTime") && !strings.Contains(typeName, "spanner.NullDate") {
			return errors.Newf("the token column %s reads %s as a date, and the field is typed %s; a date role formats a DATE or TIMESTAMP column", fact.Column, fact.Source, typeName)
		}
	default:
		if kind != resource.ValueKindString || slice {
			return errors.Newf("the token column %s reads %s as text, and the field is typed %s; a search fact goes on a text field", fact.Column, fact.Source, typeName)
		}
	}

	return nil
}

// resolveSearchBranches resolves every table-backed resource's @searchAlso once all are
// extracted: the child is a table-backed resource one foreign key away from the
// parent's single-column key, under the same tenancy, and its field carries a search
// fact; the branch is then what the generated SearchBranches declares.
func (c *client) resolveSearchBranches(resources []*resourceInfo) error {
	byName := make(map[string]*resourceInfo, len(resources))
	for _, res := range resources {
		byName[res.Name()] = res
	}

	var errs []error
	for _, res := range resources {
		for _, decl := range res.searchAlso {
			branch, err := c.resolveSearchBranch(res, decl, byName)
			if err != nil {
				errs = append(errs, errors.Wrapf(err, "struct %s: @%s(%s)", res.Name(), searchAlsoKeyword, decl.target))

				continue
			}
			res.SearchBranches = append(res.SearchBranches, branch)
		}
	}
	if len(errs) > 0 {
		return errors.Wrap(errors.Join(errs...), "resolveSearchBranch()")
	}

	return nil
}

// resolveSearchBranch resolves one declaration: the parent's shape, the child field,
// the foreign key, the tenancy, then the branch.
func (c *client) resolveSearchBranch(parent *resourceInfo, decl searchAlsoDecl, byName map[string]*resourceInfo) (*searchBranch, error) {
	if parent.PkCount != 1 {
		return nil, errors.Newf("the box over %s joins the child's rows through the parent's key, and %s declares %d key columns; a search branch needs one", parent.Name(), parent.Name(), parent.PkCount)
	}
	if parent.DomainBinding != nil && len(parent.DomainBinding.Path) > 0 {
		return nil, errors.Newf("%s resolves its tenant through a join path, which the child's branch cannot carry; a searched parent binds its tenant on the row", parent.Name())
	}
	child, field, err := c.searchBranchTarget(parent, decl, byName)
	if err != nil {
		return nil, err
	}
	join, err := c.searchBranchJoin(parent, child, decl)
	if err != nil {
		return nil, err
	}
	if err := checkSearchBranchTenancy(parent, child); err != nil {
		return nil, err
	}

	branch := &searchBranch{child: child, childField: field}
	childName, fieldName, _ := strings.Cut(decl.target, ".")
	childTenant := bareTenantColumn(child)
	branch.Name = caser.ToCamel(childName) + "." + caser.ToCamel(fieldName)
	branch.Resource = accesstypes.Resource(c.pluralize(childName))
	branch.Field = accesstypes.Field(fieldName)
	if !field.IsPrimaryKey {
		branch.Tag = accesstypes.Tag(field.WireName())
	}
	branch.Table = c.pluralize(childName)
	branch.Column = fieldColumn(field)
	branch.JoinColumn = fieldColumn(join)
	branch.TenantColumn = childTenant
	branch.Token, branch.Index, branch.Role = field.Search.Token, field.Search.Index, field.Search.Role
	branch.Anchors, branch.Contains, branch.Zone = field.Search.Anchors, field.Search.Contains, field.Search.Zone
	branch.PII = field.IsPII()

	if !join.IsPrimaryKey && !slices.Contains(c.indexStoring(branch.Table, field.Search.Index), branch.JoinColumn) {
		parent.searchWarnings = append(parent.searchWarnings, SearchBranchStoringWarning{Resource: parent.Name(), Child: branch.Table, IndexName: field.Search.Index, JoinColumn: branch.JoinColumn})
	}

	return branch, nil
}

// searchBranchTarget finds the child resource and field a declaration names: a
// table-backed resource of the package other than the parent, with a field carrying
// the search fact.
func (c *client) searchBranchTarget(parent *resourceInfo, decl searchAlsoDecl, byName map[string]*resourceInfo) (*resourceInfo, *resourceField, error) {
	childName, fieldName, _ := strings.Cut(decl.target, ".")
	child, ok := byName[childName]
	if !ok {
		return nil, nil, errors.Newf("%s is not a table-backed resource of this package", childName)
	}
	if child == parent {
		return nil, nil, errors.Newf("%s names its own field; the resource's own fields join the box through their search facts", childName)
	}
	var field *resourceField
	for _, f := range child.Fields {
		if f.Name() == fieldName {
			field = f
		}
	}
	if field == nil {
		return nil, nil, errors.Newf("%s has no field %s", childName, fieldName)
	}
	if field.Search == nil || field.Search.Token == "" {
		return nil, nil, errors.Newf("%s.%s carries no search fact; a token column over %s in %s's search index gives it one", childName, fieldName, fieldColumn(field), c.pluralize(childName))
	}

	return child, field, nil
}

// searchBranchJoin finds the child's foreign key to the parent's key the branch joins
// through: the one there is, or the one via: names where there are several.
func (c *client) searchBranchJoin(parent, child *resourceInfo, decl searchAlsoDecl) (*resourceField, error) {
	childName, _, _ := strings.Cut(decl.target, ".")
	parentKey := fieldColumn(parent.PrimaryKey())
	parentTable := c.pluralize(parent.Name())
	var joins []*resourceField
	for _, f := range child.Fields {
		if f.IsForeignKey && f.ReferencedResource == parentTable && f.ReferencedField == parentKey {
			joins = append(joins, f)
		}
	}
	if decl.via != "" {
		joins = slices.DeleteFunc(joins, func(f *resourceField) bool { return fieldColumn(f) != decl.via && f.Name() != decl.via })
	}
	switch {
	case len(joins) == 0 && decl.via != "":
		return nil, errors.Newf("%s has no foreign key %s referencing %s.%s", childName, decl.via, parentTable, parentKey)
	case len(joins) == 0:
		return nil, errors.Newf("%s has no foreign key referencing %s.%s; a search branch is one hop down a foreign key", childName, parentTable, parentKey)
	case len(joins) > 1:
		names := make([]string, 0, len(joins))
		for _, f := range joins {
			names = append(names, fieldColumn(f))
		}

		return nil, errors.Newf("%s has %d foreign keys referencing %s (%s); name the one the box joins through with %s:", childName, len(joins), parentTable, strings.Join(names, ", "), searchViaArgKey)
	}

	return joins[0], nil
}

// checkSearchBranchTenancy refuses a child under another tenancy than its parent's.
func checkSearchBranchTenancy(parent, child *resourceInfo) error {
	if child.DomainBinding != nil && len(child.DomainBinding.Path) > 0 {
		return errors.Newf("%s resolves its tenant through a join path, which its branch cannot carry; a searched child binds its tenant on the row", child.Name())
	}
	if (bareTenantColumn(parent) == "") != (bareTenantColumn(child) == "") {
		return errors.Newf("%s and %s are not under the same tenancy: a tenant-scoped parent searches a tenant-scoped child, and a global parent a global child", parent.Name(), child.Name())
	}

	return nil
}

// resolveViewSearchFacts reads a view's authored search tags: search:"Table.Column"
// names the table column whose fact the field carries, read off the schema as a
// table's own are. Refused where the value is malformed, the table or column is
// unknown, or the column has no fact.
func (c *client) resolveViewSearchFacts(res *resourceInfo, pStruct *parser.Struct, annotations genlang.StructAnnotations) error {
	if err := rejectSearchAlso(pStruct, annotations, "virtual resource"); err != nil {
		return err
	}
	// The table each search index belongs to, for the key-set condition below.
	indexTables := make(map[string]string)
	for _, field := range res.Fields {
		tag, ok := field.LookupTag(searchTagKey)
		if !ok {
			continue
		}
		table, column, found := strings.Cut(strings.TrimSpace(tag), ".")
		if !found || table == "" || column == "" {
			return errors.Newf("struct %s field %s: %s:%q names the table column the field carries as Table.Column", pStruct.Name(), field.Name(), searchTagKey, tag)
		}
		meta, ok := c.tableMap[table]
		if !ok {
			return errors.Newf("struct %s field %s: %s:%q names table %s, which the schema does not have", pStruct.Name(), field.Name(), searchTagKey, tag, table)
		}
		if _, ok := meta.Columns[column]; !ok {
			return errors.Newf("struct %s field %s: %s:%q names column %s, which %s does not have", pStruct.Name(), field.Name(), searchTagKey, tag, column, table)
		}
		facts, err := tableSearchFacts(table, meta, "", true)
		if err != nil {
			return errors.Wrapf(err, "struct %s field %s", pStruct.Name(), field.Name())
		}
		fact, hasToken := facts.tokens[column]
		lower, hasLower := facts.lower[column]
		if !hasToken && !hasLower {
			return errors.Newf("struct %s field %s: %s.%s carries no search fact; a token column over it in %s's search index, or a lowercased stored column leading an index, gives it one", pStruct.Name(), field.Name(), table, column, table)
		}
		spec := &resource.SearchSpec{Lower: lower}
		if hasToken {
			if err := checkSearchFieldType(field, fact); err != nil {
				return errors.Wrapf(err, "struct %s field %s", pStruct.Name(), field.Name())
			}
			spec.Token, spec.Index, spec.Role = fact.Column, fact.Index, fact.Role
			spec.Anchors, spec.Contains, spec.Diacritics, spec.Zone = fact.Anchors, fact.Contains, fact.Diacritics, fact.Zone
			indexTables[fact.Index] = table
		} else if kind, slice := valueKindOf(field.GoType()); kind != resource.ValueKindString || slice {
			return errors.Newf("struct %s field %s: %s.%s gives a case-folded startswith, which a text field answers, and the field is typed %s", pStruct.Name(), field.Name(), table, column, typeStringer(field.GoType()))
		}
		field.Search = spec
	}

	return c.checkViewKeySetJoins(res, pStruct, indexTables)
}

// checkViewKeySetJoins applies the key-set statement's condition to a view whose box
// spans several search indexes: each index of a table other than the view's root is
// reached through a foreign key of the root table, which needs an index on (tenant
// column, join column), on the join column alone where the view is global; the proof
// measured 5,041 rows scanned without it against 58 with it. A view without @rowsOf has
// no known root, so it is refused naming the way out.
func (c *client) checkViewKeySetJoins(res *resourceInfo, pStruct *parser.Struct, indexTables map[string]string) error {
	if len(indexTables) < 2 {
		return nil
	}
	tables := slices.Sorted(maps.Values(indexTables))
	if res.rowsOfArg == nil {
		return errors.Newf("struct %s: the search box reaches %d search indexes (%s), which the statement reads through the view's root table; declare @%s(Table) so the generator knows it, or project one table's token columns", pStruct.Name(), len(indexTables), strings.Join(tables, ", "), rowsOfKeyword)
	}
	root := strings.TrimSpace(string(*res.rowsOfArg))
	rootMeta, ok := c.tableMap[root]
	if !ok {
		return errors.Newf("struct %s: @%s(%s) names a table the schema does not have", pStruct.Name(), rowsOfKeyword, root)
	}
	tenant := bareTenantColumn(res)
	for _, index := range slices.Sorted(maps.Keys(indexTables)) {
		table := indexTables[index]
		if table == root {
			continue
		}
		var joins []string
		for name, column := range rootMeta.Columns {
			if column.IsForeignKey && column.ReferencedTable == table {
				joins = append(joins, name)
			}
		}
		if len(joins) == 0 {
			return errors.Newf("struct %s: the search box reaches %s's search index %s, and %s has no foreign key to %s; a view's box reaches another table's index through a foreign key of its root table", pStruct.Name(), table, index, root, table)
		}
		slices.Sort(joins)
		for _, join := range joins {
			if hasIndexOn(rootMeta, tenant, join) {
				continue
			}
			columns := join
			if tenant != "" {
				columns = tenant + ", " + join
			}

			return errors.Newf("struct %s: the search box reaches %s's search index %s through %s.%s, and %s has no index on (%s), so every search would scan its rows for the keys found; wanted: CREATE INDEX %sBy%s ON %s(%s)", pStruct.Name(), table, index, root, join, root, columns, root, strings.ReplaceAll(columns, ", ", ""), root, columns)
		}
	}

	return nil
}

// hasIndexOn reports whether a seek index of the table has the key (first, second), or
// leads with second where first is "".
func hasIndexOn(meta *tableMetadata, first, second string) bool {
	want := []string{second}
	if first != "" {
		want = []string{first, second}
	}
	for _, index := range meta.Indexes {
		if index.Search || index.NullFiltered || len(index.Key) < len(want) {
			continue
		}
		matches := true
		for i, column := range want {
			if index.Key[i].Column != column {
				matches = false

				break
			}
		}
		if matches {
			return true
		}
	}

	return false
}

// SearchTag renders the search tag the generated list and read request structs carry:
// the field's vocabulary, nothing on a field with none.
func (f *resourceField) SearchTag() string {
	if f.Search == nil {
		return ""
	}

	return fmt.Sprintf("%s:%q", searchOutTagKey, f.Search.Tag())
}

// TypescriptSearch renders the matches the field answers for the TypeScript metadata,
// as a quoted list; "" where it answers none.
func (f *resourceField) TypescriptSearch() string {
	if f.Search == nil {
		return ""
	}

	return quotedList(f.Search.Matches())
}

// TextIdentEligible reports whether the generated query builder gives the field a text
// identifier: a text field that answers at least one match.
func (f *resourceField) TextIdentEligible() bool {
	return f.Search != nil && len(f.Search.Matches()) > 0
}

// AnswersMatch reports whether the field answers the named match, for the per-field
// identifier's methods.
func (f *resourceField) AnswersMatch(operator string) bool {
	return f.Search != nil && slices.Contains(f.Search.Matches(), operator)
}

// SearchTagValue is the tag's value alone, for the generated identifier.
func (f *resourceField) SearchTagValue() string {
	if f.Search == nil {
		return ""
	}

	return f.Search.Tag()
}

// quotedList renders strings as a single-quoted, comma-separated list.
func quotedList(values []string) string {
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, "'"+value+"'")
	}

	return strings.Join(quoted, ", ")
}

// SearchFieldNames lists what the resource's search box searches, for the TypeScript
// metadata: the fields with the search fact by wire name, in declaration order, then
// the @searchAlso branches by dotted name.
func (r *resourceInfo) SearchFieldNames() []string {
	var names []string
	for _, field := range r.Fields {
		if field.Search != nil && field.Search.JoinsBox() && field.WireName() != "" {
			names = append(names, field.WireName())
		}
	}
	for _, branch := range r.SearchBranches {
		names = append(names, branch.Name)
	}

	return names
}

// TypescriptSearchFields renders SearchFieldNames as a quoted list.
func (r *resourceInfo) TypescriptSearchFields() string {
	return quotedList(r.SearchFieldNames())
}

// HasSearchBox reports whether the resource's box searches anything: a field with the
// search fact, or a branch.
func (r *resourceInfo) HasSearchBox() bool {
	return len(r.SearchFieldNames()) > 0
}

// SearchColumns lists the fields that join the box as the generated query builder
// declares them: the field name the builder's identifiers use, and the tag.
func (r *resourceInfo) SearchColumns() []resource.SearchColumn {
	var columns []resource.SearchColumn
	for _, field := range r.Fields {
		if field.Search != nil && field.Search.JoinsBox() {
			columns = append(columns, resource.SearchColumn{Column: field.Name(), Tag: field.Search.Tag()})
		}
	}

	return columns
}

// SearchKeyColumn is the resource's single-column key as the generated query builder
// names it, which a box over several indexes joins its key sets on; "" when the
// resource declares no key or several.
func (r *resourceInfo) SearchKeyColumn() string {
	if r.keyCount() != 1 {
		return ""
	}

	return r.PrimaryKey().Name()
}

// SearchTag renders search:"memory" onto a computed resource's allow_filter text field:
// the handler evaluates its matches and the box over the rows the body yields.
func (c *computedField) SearchTag() string {
	if !c.evaluatedSearch() {
		return ""
	}

	return fmt.Sprintf("%s:%q", searchOutTagKey, (&resource.SearchSpec{InMemory: true}).Tag())
}

// evaluatedSearch reports whether the field is searched in memory: allow_filter on a
// text leaf.
func (c *computedField) evaluatedSearch() bool {
	if _, ok := c.LookupTag(allowFilterTagKey); !ok {
		return false
	}
	kind, slice := valueKindOf(c.GoType())

	return kind == resource.ValueKindString && !slice
}

// TypescriptSearch renders the three matches an evaluated field answers; "" otherwise.
func (c *computedField) TypescriptSearch() string {
	if !c.evaluatedSearch() {
		return ""
	}

	return quotedList((&resource.SearchSpec{InMemory: true}).Matches())
}

// TypescriptSearchFields renders the fields the computed resource's box searches.
func (c *computedResource) TypescriptSearchFields() string {
	var names []string
	for _, field := range c.Fields {
		if field.evaluatedSearch() {
			names = append(names, caser.ToCamel(field.Name()))
		}
	}

	return quotedList(names)
}
