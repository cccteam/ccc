type packageDir string

func (p packageDir) Dir() string {
	if strings.HasSuffix(string(p), ".go") {
		s := strings.TrimSuffix(string(p), filepath.Base(string(p)))
		if s != "" {
			s = s[:len(s)-1]
		}

		return s
	}

	return string(p)
}

func (p packageDir) Package() string {
	if strings.HasSuffix(string(p), ".go") {
		return filepath.Base(filepath.Dir(string(p)))
	}

	return filepath.Base(string(p))
}

func handlerTypes() []HandlerType {
	return []HandlerType{
		AllHandlers,
		ListHandler,
		ReadHandler,
		PatchHandler,
	}
}

func routeTypes() []RouteType {
	return []RouteType{
		AllRoutes,
	}
}

// validSuppressArgs returns the set of valid arguments accepted by the @suppress() directive.
func validSuppressArgs() []string {
	args := make([]string, 0, len(handlerTypes())+len(routeTypes()))
	for _, ht := range handlerTypes() {
		args = append(args, string(ht))
	}
	for _, rt := range routeTypes() {
		args = append(args, string(rt))
	}

	return args
}

func validComputedSuppressArgs() []string {
	return []string{
		string(AllHandlers),
		string(ListHandler),
		string(ReadHandler),
		string(AllRoutes),
	}
}

func (h HandlerType) template() string {
	switch h {
	case ReadHandler:
		return readTemplate
	case ListHandler:
		return listTemplate
	case PatchHandler:
		return patchTemplate
	default:
		panic(fmt.Sprintf("template(): unknown handler type: %s", h))
	}
}

// method returns the proper http method type for a HandlerType
func (h HandlerType) method() string {
	switch h {
	case ReadHandler, ListHandler:
		return http.MethodGet
	case PatchHandler:
		return http.MethodPatch
	default:
		panic(fmt.Sprintf("Method(): unknown handler type: %s", h))
	}
}

// httpMethodConstant returns the net/http constant name for an http method
// (e.g. "GET" -> "http.MethodGet").
func httpMethodConstant(method string) string {
	return "http.Method" + strcase.ToPascal(method)
}

