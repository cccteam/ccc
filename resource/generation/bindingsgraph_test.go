// bindingsGraphFixture assembles fixture resources the way Generate does: the
// named structs through the binding resolver and, when asked, the StatefulTask
// workflow chain through workflow resolution, so the synthesized state paths
// are present.
func bindingsGraphFixture(t *testing.T, structs map[string]*parser.Struct, names []string, withWorkflow bool) (r *resourceGenerator, dir string) {
	t.Helper()

	c := stateFixtureClient()
	var resources []*resourceInfo
	for _, name := range names {
		res, err := resolveFixtureBindings(t, c, structs, name)
		if err != nil {
			t.Fatalf("resolveFixtureBindings(%s) error = %v", name, err)
		}
		resources = append(resources, res)
	}
	if withWorkflow {
		root := buildWorkflowFixture(t, c, structs, "StatefulTask")
		part := buildWorkflowFixture(t, c, structs, "TaskPart")
		order := buildWorkflowFixture(t, c, structs, "PartOrder")
		if err := c.resolveWorkflows([]*resourceInfo{root, part, order}); err != nil {
			t.Fatalf("resolveWorkflows() error = %v", err)
		}
		resources = append(resources, root, part, order)
	}

	dir = t.TempDir()
	r = &resourceGenerator{client: c}
	r.resources = resources
	r.resource = packageDir(dir)

	return r, dir
}

// TestGenerateBindingsGraph pins the DOT review surface for bindings: every
// path drawn hop by hop with a shared hop drawn once, every bare binding
// listed in its resource's box and pointed at its table when it sits on a
// foreign key (the state column's enum table excepted), landed tables dashed
// and resolved to their struct where one is parsed, the requester entering
// each anchor once, the legend, and no file for a package with nothing to draw.
func TestGenerateBindingsGraph(t *testing.T) {
	t.Parallel()

	structs := fixtureStructs(loadFixture(t, "bindingfixture"))

	tests := []struct {
		name         string
		resources    []string
		withWorkflow bool
		// want is the whole file; "" means no file is written.
		want string
	}{
		{
			name: "every path kind drawn hop by hop, a shared hop once, bare bindings absent",
			// MaintenanceTask: a one-hop and a two-hop attribute path, two bare
			// attributes listed in its box, and a bare @domain (not listed).
			// PathTenantTask and PathTenantLog: one- and two-hop domain paths sharing
			// their hop into Berths; PathTenantLog's bare task attribute sits on the
			// foreign key, so a reference edge points it at PathTenantTask. HomeProfile:
			// a dotted subject value, so a plain box. CrewMember and UserProfile: a bare
			// set and a bare value, listed and entered by the requester. Ship: a parsed
			// resource paths only land on. The workflow chain: TaskPart's and
			// PartOrder's synthesized state paths share their hop into the root, whose
			// own bare state binding is listed with no edge to its enum table.
			resources:    []string{"MaintenanceTask", "PathTenantTask", "PathTenantLog", "HomeProfile", "CrewMember", "UserProfile", "Ship"},
			withWorkflow: true,
			want: `// Code generated by resourcegeneration. DO NOT EDIT.
// Bindings: every attribute and subject binding this package declares. A box per
// declaring resource lists its bare bindings as ` + "`name: column`" + `; dashed boxes are
// the tables a path lands on or a foreign key points at; the subject ellipse is
// the requester, entering each anchor once with every name it yields there. One
// edge per hop, drawn once however many paths share it: solid for @attribute,
// dotted for @domain, dashed for a subject binding, labeled ` + "`name: column`" + ` on a
// continuing hop and ` + "`name: column ⇒ column`" + ` where the path terminates; a thin
// grey edge points a bare binding on a foreign key at its table. Facts only: no
// grant or condition is drawn.
digraph Bindings {
	rankdir=LR;
	node [shape=box];
	"CrewMember" [label=<<table border="0" cellborder="0" cellspacing="0" cellpadding="1"><tr><td align="left"><b>CrewMember</b></td></tr><tr><td align="left">subject.crews: CrewId</td></tr></table>>];
	"HomeProfile";
	"MaintenanceTask" [label=<<table border="0" cellborder="0" cellspacing="0" cellpadding="1"><tr><td align="left"><b>MaintenanceTask</b></td></tr><tr><td align="left">crew: CrewId</td></tr><tr><td align="left">estimatedCost: EstimatedCost</td></tr></table>>];
	"PartOrder";
	"PathTenantLog" [label=<<table border="0" cellborder="0" cellspacing="0" cellpadding="1"><tr><td align="left"><b>PathTenantLog</b></td></tr><tr><td align="left">task: TaskId</td></tr></table>>];
	"PathTenantTask";
	"StatefulTask" [label=<<table border="0" cellborder="0" cellspacing="0" cellpadding="1"><tr><td align="left"><b>StatefulTask</b></td></tr><tr><td align="left">state: State</td></tr></table>>];
	"TaskPart";
	"UserProfile" [label=<<table border="0" cellborder="0" cellspacing="0" cellpadding="1"><tr><td align="left"><b>UserProfile</b></td></tr><tr><td align="left">subject.approvalLimit: ApprovalLimit</td></tr></table>>];
	"Berths" [style=dashed];
	"Ship" [style=dashed];
	"Stations" [style=dashed];
	"subject" [shape=ellipse];
	"Berths" -> "Stations" [label="sector: StationId ⇒ Sector"];
	"MaintenanceTask" -> "Berths" [label="sector: BerthId"];
	"MaintenanceTask" -> "Ship" [label="shipClass: ShipId ⇒ Class"];
	"PartOrder" -> "TaskPart" [label="state: PartId"];
	"TaskPart" -> "StatefulTask" [label="state: TaskId ⇒ State"];
	"PathTenantLog" -> "PathTenantTask" [style=dotted, label="domain: TaskId"];
	"PathTenantTask" -> "Berths" [style=dotted, label="domain: BerthId ⇒ StationId"];
	"HomeProfile" -> "Stations" [style=dashed, label="homeSector: StationId ⇒ Sector"];
	"subject" -> "CrewMember" [style=dashed, label="crews: UserId"];
	"subject" -> "HomeProfile" [style=dashed, label="homeSector: UserId"];
	"subject" -> "UserProfile" [style=dashed, label="approvalLimit: UserId"];
	"PathTenantLog" -> "PathTenantTask" [color=gray55, fontcolor=gray35, arrowhead=vee, arrowsize=0.6, label="task"];
	subgraph cluster_legend {
		label="legend";
		"declares a binding" [shape=box];
		"landed on / pointed at" [shape=box, style=dashed];
		"requester" [shape=ellipse];
		"legend:attribute" [shape=point];
		"legend:attribute:to" [shape=point];
		"legend:domain" [shape=point];
		"legend:domain:to" [shape=point];
		"legend:subject" [shape=point];
		"legend:subject:to" [shape=point];
		"legend:reference" [shape=point];
		"legend:reference:to" [shape=point];
		"legend:attribute" -> "legend:attribute:to" [label="@attribute path"];
		"legend:domain" -> "legend:domain:to" [style=dotted, label="@domain path"];
		"legend:subject" -> "legend:subject:to" [style=dashed, label="@subjectSet / @subjectValue"];
		"legend:reference" -> "legend:reference:to" [color=gray55, fontcolor=gray35, arrowhead=vee, arrowsize=0.6, label="bare binding on a foreign key"];
	}
}
`,
		},
		{
			// A domain path alone would draw; a resource with no binding at all does not.
			name:      "a package declaring no binding writes no file",
			resources: []string{"Ship"},
			want:      "",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			r, dir := bindingsGraphFixture(t, structs, tt.resources, tt.withWorkflow)
			if err := r.generateBindingsGraph(); err != nil {
				t.Fatalf("generateBindingsGraph() error = %v", err)
			}

			content, err := os.ReadFile(filepath.Join(dir, "zz_gen_bindings.dot"))
			switch {
			case tt.want == "" && err == nil:
				t.Fatalf("generateBindingsGraph() wrote a file for a package with nothing to draw:\n%s", content)
			case tt.want == "" && os.IsNotExist(err):
				return
			case err != nil:
				t.Fatalf("reading bindings graph: %v", err)
			}
			if got := string(content); got != tt.want {
				t.Errorf("bindings graph mismatch\n--- got\n%s\n--- want\n%s", got, tt.want)
			}
		})
	}
}
