// bindingsGraphFixture assembles fixture resources the way Generate does: the
// named structs through the binding resolver and, when asked, the StatefulTask
// workflow chain through workflow resolution, so the synthesized state paths
// are present.
func bindingsGraphFixture(t *testing.T, structs map[string]*parser.Struct, names []string, withWorkflow bool) (r *resourceGenerator, dir string) {
	t.Helper()

	c := stateFixtureClient()
	var resources []*resourceInfo
	for _, name := range names {
		res, err := resolveFixtureBindings(t, c, structs, name)
		if err != nil {
			t.Fatalf("resolveFixtureBindings(%s) error = %v", name, err)
		}
		resources = append(resources, res)
	}
	if withWorkflow {
		root := buildWorkflowFixture(t, c, structs, "StatefulTask")
		part := buildWorkflowFixture(t, c, structs, "TaskPart")
		order := buildWorkflowFixture(t, c, structs, "PartOrder")
		if err := c.resolveWorkflows([]*resourceInfo{root, part, order}); err != nil {
			t.Fatalf("resolveWorkflows() error = %v", err)
		}
		resources = append(resources, root, part, order)
	}

	dir = t.TempDir()
	r = &resourceGenerator{client: c}
	r.resources = resources
	r.resource = packageDir(dir)

	return r, dir
}

// TestGenerateBindingsGraph pins the DOT review surface for join-path
// bindings: every kind with a path drawn hop by hop, a hop two paths share
// drawn once, bare bindings absent, landed tables dashed and resolved to their
// struct where one is parsed, the requester at the start of a subject path,
// the legend, and no file for a package with nothing to draw.
func TestGenerateBindingsGraph(t *testing.T) {
	t.Parallel()

	structs := fixtureStructs(loadFixture(t, "bindingfixture"))

	tests := []struct {
		name         string
		resources    []string
		withWorkflow bool
		// want is the whole file; "" means no file is written.
		want string
	}{
		{
			name: "every path kind drawn hop by hop, a shared hop once, bare bindings absent",
			// MaintenanceTask: a one-hop and a two-hop attribute path, a bare @domain
			// and two bare attributes (not drawn). PathTenantTask and PathTenantLog:
			// one- and two-hop domain paths sharing their hop into Berths. HomeProfile:
			// a dotted subject value. CrewMember: a bare subject set (not drawn, so the
			// resource is absent). Ship: a parsed resource paths only land on. The
			// workflow chain: TaskPart's and PartOrder's synthesized state paths share
			// their hop into the root.
			resources:    []string{"MaintenanceTask", "PathTenantTask", "PathTenantLog", "HomeProfile", "CrewMember", "Ship"},
			withWorkflow: true,
			want: `// Code generated by resourcegeneration. DO NOT EDIT.
// Bindings: every join-path binding this package declares. Solid boxes are the
// resources declaring a path; dashed boxes are the tables a path only lands on;
// the subject ellipse is the requester. One edge per hop, drawn once however
// many paths share it: solid for @attribute, dotted for @domain, dashed for a
// subject binding, labeled ` + "`name: column`" + ` on a continuing hop and
// ` + "`name: column ⇒ column`" + ` where the path terminates. Facts only: no grant or
// condition is drawn.
digraph Bindings {
	rankdir=LR;
	node [shape=box];
	"HomeProfile";
	"MaintenanceTask";
	"PartOrder";
	"PathTenantLog";
	"PathTenantTask";
	"TaskPart";
	"Berths" [style=dashed];
	"Ship" [style=dashed];
	"StatefulTask" [style=dashed];
	"Stations" [style=dashed];
	"subject" [shape=ellipse];
	"Berths" -> "Stations" [label="sector: StationId ⇒ Sector"];
	"MaintenanceTask" -> "Berths" [label="sector: BerthId"];
	"MaintenanceTask" -> "Ship" [label="shipClass: ShipId ⇒ Class"];
	"PartOrder" -> "TaskPart" [label="state: PartId"];
	"TaskPart" -> "StatefulTask" [label="state: TaskId ⇒ State"];
	"PathTenantLog" -> "PathTenantTask" [style=dotted, label="domain: TaskId"];
	"PathTenantTask" -> "Berths" [style=dotted, label="domain: BerthId ⇒ StationId"];
	"HomeProfile" -> "Stations" [style=dashed, label="homeSector: StationId ⇒ Sector"];
	"subject" -> "HomeProfile" [style=dashed, label="homeSector: UserId"];
	subgraph cluster_legend {
		label="legend";
		"declares a path" [shape=box];
		"landed on" [shape=box, style=dashed];
		"requester" [shape=ellipse];
		"legend:attribute" [shape=point];
		"legend:attribute:to" [shape=point];
		"legend:domain" [shape=point];
		"legend:domain:to" [shape=point];
		"legend:subject" [shape=point];
		"legend:subject:to" [shape=point];
		"legend:attribute" -> "legend:attribute:to" [label="@attribute"];
		"legend:domain" -> "legend:domain:to" [style=dotted, label="@domain"];
		"legend:subject" -> "legend:subject:to" [style=dashed, label="@subjectSet / @subjectValue"];
	}
}
`,
		},
		{
			name:      "a package with only bare bindings writes no file",
			resources: []string{"CrewMember", "UserProfile"},
			want:      "",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			r, dir := bindingsGraphFixture(t, structs, tt.resources, tt.withWorkflow)
			if err := r.generateBindingsGraph(); err != nil {
				t.Fatalf("generateBindingsGraph() error = %v", err)
			}

			content, err := os.ReadFile(filepath.Join(dir, "zz_gen_bindings.dot"))
			switch {
			case tt.want == "" && err == nil:
				t.Fatalf("generateBindingsGraph() wrote a file for a package with nothing to draw:\n%s", content)
			case tt.want == "" && os.IsNotExist(err):
				return
			case err != nil:
				t.Fatalf("reading bindings graph: %v", err)
			}
			if got := string(content); got != tt.want {
				t.Errorf("bindings graph mismatch\n--- got\n%s\n--- want\n%s", got, tt.want)
			}
		})
	}
}
