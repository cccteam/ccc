// webSiteProgram renders a site's generator program under the generated router: its
// default outlet bound to the auth and serving a browser application at the root, with
// the generated client in the site's workspace.
func webSiteProgram(site, auth string) string {
	return program("apps/"+site+"/pkg/resources",
		`generation.GenerateHandlers("apps/`+site+`/app"),`,
		`generation.GenerateRouter(),`,
		`generation.GenerateRoutes("apps/`+site+`/pkg/router", "api", generation.Auth("example.com/harbor/pkg/auth/`+auth+`", generation.PasswordMethod()), generation.WebApp("/")),`,
		`generation.GenerateTypescript("apps/`+site+`/web/`+site+`/src/app/core/service"),`,
	)
}

// webAngular renders a site's workspace configuration: one project named for the site.
func webAngular(site string) string {
	return `{"projects": {"` + site + `": {"root": "` + site + `", "sourceRoot": "` + site + `/src"}}}` + "\n"
}

// webConstants renders the generated constants exporting the auth's user surface.
func webConstants(auth string) string {
	return "// Code generated by resourcegeneration. DO NOT EDIT.\nimport { Method, Resource } from '@cccteam/resource';\n\nexport const Resources = {\n" +
		"  FeatureFlags: 'FeatureFlags' as Resource,\n" +
		"  " + auth + "Roles: '" + auth + "Roles' as Resource,\n" +
		"  " + auth + "Seats: '" + auth + "Seats' as Resource,\n" +
		"  " + auth + "Users: '" + auth + "Users' as Resource,\n" +
		"};\n\nexport const Methods = {\n  Set" + auth + "UserPassword: 'Set" + auth + "UserPassword' as Method,\n};\n"
}

// webUsersPage renders a users page over the auth's user surface: its users and roles
// resources, taken from the generated constants.
func webUsersPage(auth string) string {
	return "import { Component } from '@angular/core';\nimport { Permissions, Resources } from '@app/service/zz_gen_constants';\n\nexport class UsersComponent {\n" +
		"  readonly scope = { resource: Resources." + auth + "Users, permission: Permissions.List };\n" +
		"  readonly roles = { resource: Resources." + auth + "Roles, permission: Permissions.List };\n}\n"
}

// webAppConfig renders an application configuration whose HttpClient names the cookie.
func webAppConfig(cookie string) string {
	return "import { provideHttpClient, withInterceptors, withXsrfConfiguration } from '@angular/common/http';\n\nexport const appConfig = {\n  providers: [\n" +
		"    provideHttpClient(withInterceptors([apiVersionInterceptor]), withXsrfConfiguration({ cookieName: '" + cookie + "' })),\n  ],\n};\n"
}

// webAuth renders an auth package constructing its session Auth, naming its XSRF cookie
// as the skeleton's auths do (XSRFCookie, Name + "-xsrf") or leaving it to the library.
func webAuth(name string, namesCookie bool) string {
	option := ""
	if namesCookie {
		option = ", session.WithXSRFCookieName(XSRFCookie)"
	}

	return `package ` + name + `

import (
	"context"

	cloudspanner "cloud.google.com/go/spanner"
	"github.com/cccteam/session"
	"github.com/cccteam/session/sessionstorage"
)

const (
	Name        = "` + name + `"
	TablePrefix = "` + pascal(name) + `"
	XSRFCookie  = Name + "-xsrf"
)

type Auth struct {
	session *session.Auth[session.NoCustomData, session.NoCustomData, *cloudspanner.ReadWriteTransaction]
}

func New(ctx context.Context, db *cloudspanner.Client, key string) (*Auth, error) {
	s, err := session.NewAuth[session.NoCustomData, session.NoCustomData](sessionstorage.NewSpannerAuth(db), key,
		session.WithSessionTableName(TablePrefix+"Sessions")` + option + `)
	if err != nil {
		return nil, err
	}
	session.PasswordSignIn(s)

	return &Auth{session: s}, nil
}
`
}

// webSite lays out one site: its program bound to the auth, its workspace, the generated
// constants exporting the auth's surface, and a users page and application configuration
// naming the page's auth and the cookie.
func webSite(files map[string]string, site, auth, pageAuth, cookie string) {
	web := "apps/" + site + "/web/"
	files["cmd/generate/"+site+"/main.go"] = webSiteProgram(site, auth)
	files[web+"angular.json"] = webAngular(site)
	files[web+site+"/src/app/core/service/zz_gen_constants.ts"] = webConstants(pascal(auth))
	files[web+site+"/src/app/components/ui/users/users.component.ts"] = webUsersPage(pascal(pageAuth))
	files[web+site+"/src/app/app.config.ts"] = webAppConfig(cookie)
}

func TestWebWired(t *testing.T) {
	t.Parallel()

	const (
		portalUsers  = "apps/portal/web/portal/src/app/components/ui/users/users.component.ts"
		portalConfig = "apps/portal/web/portal/src/app/app.config.ts"
		consoleLine  = "console: apps/console/web/console/src names 2 resource(s) its generated client exports and the staff auth's XSRF cookie (staff-xsrf)"
		portalLine   = "portal: apps/portal/web/portal/src names 2 resource(s) its generated client exports and the members auth's XSRF cookie (members-xsrf)"
	)
	auths := map[string]string{
		"pkg/auth/staff/staff.go":     webAuth("staff", true),
		"pkg/auth/members/members.go": webAuth("members", true),
	}
	// bound is the sites layout with each site's browser application bound to its auth.
	bound := func() map[string]string {
		files := map[string]string{}
		for rel, content := range auths {
			files[rel] = content
		}
		webSite(files, "console", "staff", "staff", "staff-xsrf")
		webSite(files, "portal", "members", "members", "members-xsrf")

		return files
	}
	// stale is the sites layout after the portal's outlet was bound to the members auth
	// while its browser application, the console's copy, still names the staff auth.
	stale := func() map[string]string {
		files := bound()
		webSite(files, "portal", "members", "staff", "staff-xsrf")

		return files
	}
	// flat is the flat layout with two browser projects in one workspace: the console on
	// the default outlet with the staff auth, the portal outlet with the members auth.
	flat := func() map[string]string {
		files := map[string]string{}
		for rel, content := range auths {
			files[rel] = content
		}
		files["cmd/generate/main.go"] = program("pkg/resources",
			`generation.GenerateHandlers("app"),`,
			`generation.GenerateRouter(),`,
			`generation.GenerateRoutes("pkg/router", "console/api", generation.Auth("example.com/harbor/pkg/auth/staff", generation.PasswordMethod()), generation.WebApp("/console")),`,
			`generation.WithRouterOutlet("portal", "portal/api", generation.Auth("example.com/harbor/pkg/auth/members", generation.PasswordMethod()), generation.WebApp("/portal")),`,
			`generation.GenerateTypescript("web/console/src/app/core/service"),`,
			`generation.GenerateTypescript("web/portal/src/app/core/service", generation.ForOutlet("portal")),`,
		)
		files["web/angular.json"] = `{"projects": {"console": {"root": "console", "sourceRoot": "console/src"}, "portal": {"root": "portal", "sourceRoot": "portal/src"}}}` + "\n"
		files["web/console/src/app/core/service/zz_gen_constants.ts"] = webConstants("Staff")
		files["web/console/src/app/components/ui/users/users.component.ts"] = webUsersPage("Staff")
		files["web/console/src/app/app.config.ts"] = webAppConfig("staff-xsrf")
		files["web/portal/src/app/core/service/zz_gen_constants.ts"] = webConstants("Members")
		files["web/portal/src/app/components/ui/users/users.component.ts"] = webUsersPage("Members")
		files["web/portal/src/app/app.config.ts"] = webAppConfig("members-xsrf")

		return files
	}

	tests := []struct {
		name        string
		files       map[string]string
		edit        func(files map[string]string)
		wantStatus  Status
		wantSummary string
		wantDetails []string
	}{
		{
			name:        "two sites bound to their auths",
			files:       bound(),
			wantStatus:  Pass,
			wantSummary: "2 browser application(s) bound to their outlets' auths",
			wantDetails: []string{consoleLine, portalLine},
		},
		{
			name:        "a site's copy of the console's browser application still names the console's auth",
			files:       stale(),
			wantStatus:  Fail,
			wantSummary: "3 browser binding problem(s)",
			wantDetails: []string{
				portalUsers + ":5: Resources.StaffUsers is not exported by apps/portal/web/portal/src/app/core/service/zz_gen_constants.ts, the portal outlet's generated client, so the browser build fails on it; rename it to a resource the client exports (the members auth's are MembersRoles, MembersSeats, MembersUsers), as impulse add auth --outlet portal writes the site's users page",
				portalUsers + ":6: Resources.StaffRoles is not exported by apps/portal/web/portal/src/app/core/service/zz_gen_constants.ts, the portal outlet's generated client, so the browser build fails on it; rename it to a resource the client exports (the members auth's are MembersRoles, MembersSeats, MembersUsers), as impulse add auth --outlet portal writes the site's users page",
				portalConfig + ":5: withXsrfConfiguration names the cookie staff-xsrf, which no auth bound to the portal outlet issues (the members auth issues members-xsrf), so the server refuses every mutating request; name members-xsrf, as impulse add auth --outlet portal writes it",
			},
		},
		{
			name:  "a client predating the outlet's binding is regenerated, not renamed around",
			files: bound(),
			edit: func(files map[string]string) {
				files["apps/portal/web/portal/src/app/core/service/zz_gen_constants.ts"] = webConstants("Staff")
			},
			wantStatus:  Fail,
			wantSummary: "2 browser binding problem(s)",
			wantDetails: []string{
				portalUsers + ":5: Resources.MembersUsers is not exported by apps/portal/web/portal/src/app/core/service/zz_gen_constants.ts, the portal outlet's generated client, so the browser build fails on it; the client exports no resource of the auth bound to the portal outlet, so it predates the binding: run go generate ./...",
				portalUsers + ":6: Resources.MembersRoles is not exported by apps/portal/web/portal/src/app/core/service/zz_gen_constants.ts, the portal outlet's generated client, so the browser build fails on it; the client exports no resource of the auth bound to the portal outlet, so it predates the binding: run go generate ./...",
			},
		},
		{
			name:  "a client not generated yet has the cookie checked alone",
			files: stale(),
			edit: func(files map[string]string) {
				delete(files, "apps/portal/web/portal/src/app/core/service/zz_gen_constants.ts")
			},
			wantStatus:  Fail,
			wantSummary: "1 browser binding problem(s)",
			wantDetails: []string{
				portalConfig + ":5: withXsrfConfiguration names the cookie staff-xsrf, which no auth bound to the portal outlet issues (the members auth issues members-xsrf), so the server refuses every mutating request; name members-xsrf, as impulse add auth --outlet portal writes it",
			},
		},
		{
			name:  "a hand-written router declares no auth, so any auth's cookie is the outlet's",
			files: bound(),
			edit: func(files map[string]string) {
				files["cmd/generate/portal/main.go"] = program("apps/portal/pkg/resources",
					`generation.GenerateHandlers("apps/portal/app"),`,
					`generation.GenerateRoutes("apps/portal/pkg/router", "api", generation.WebApp("/")),`,
					`generation.GenerateTypescript("apps/portal/web/portal/src/app/core/service"),`,
				)
			},
			wantStatus:  Pass,
			wantSummary: "2 browser application(s) bound to their outlets' auths",
			wantDetails: []string{consoleLine, portalLine},
		},
		{
			name:  "an auth naming no XSRF cookie issues the library's default",
			files: bound(),
			edit: func(files map[string]string) {
				files["pkg/auth/staff/staff.go"] = webAuth("staff", false)
			},
			wantStatus:  Fail,
			wantSummary: "1 browser binding problem(s)",
			wantDetails: []string{
				"apps/console/web/console/src/app/app.config.ts:5: withXsrfConfiguration names the cookie staff-xsrf, which no auth bound to the console outlet issues (the staff auth issues XSRF-TOKEN), so the server refuses every mutating request; name XSRF-TOKEN, as impulse add auth --outlet console writes it",
			},
		},
		{
			name:        "the flat layout's projects are read against their outlets",
			files:       flat(),
			wantStatus:  Pass,
			wantSummary: "2 browser application(s) bound to their outlets' auths",
			wantDetails: []string{"harbor: web/console/src names 2 resource(s) its generated client exports and the staff auth's XSRF cookie (staff-xsrf); web/portal/src names 2 resource(s) its generated client exports and the members auth's XSRF cookie (members-xsrf)"},
		},
		{
			name:  "no browser project is bound to a session outlet",
			files: bound(),
			edit: func(files map[string]string) {
				for _, site := range []string{"console", "portal"} {
					delete(files, "apps/"+site+"/web/angular.json")
				}
			},
			wantStatus:  Skip,
			wantSummary: "no browser project is bound to a session outlet",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			if tt.edit != nil {
				tt.edit(tt.files)
			}
			root := t.TempDir()
			write := func(rel, content string) {
				t.Helper()
				if err := os.MkdirAll(filepath.Dir(filepath.Join(root, rel)), 0o750); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(filepath.Join(root, rel), []byte(content), 0o600); err != nil {
					t.Fatal(err)
				}
			}
			write("go.mod", "module example.com/harbor\n\ngo 1.26.6\n")
			for rel, content := range tt.files {
				write(rel, content)
			}

			a, err := app.Discover(root)
			if err != nil {
				t.Fatalf("app.Discover() error = %v", err)
			}
			got := webWired{}.Run(context.Background(), &Env{App: a})
			want := Result{Name: webWired{}.Name(), Status: tt.wantStatus, Summary: tt.wantSummary, Details: tt.wantDetails}
			if diff := cmp.Diff(want, got); diff != "" {
				t.Errorf("Run() mismatch (-want +got):\n%s", diff)
			}
		})
	}
}

func TestWebWiredMeaning(t *testing.T) {
	t.Parallel()

	meaning := webWired{}.Meaning()
	for _, want := range []string{"Resources.<Auth>Users", "withXsrfConfiguration({ cookieName: '<auth>-xsrf' })", "TS2339", "impulse add auth --outlet <site>"} {
		if !strings.Contains(meaning, want) {
			t.Errorf("Meaning() lacks %q", want)
		}
	}
}
